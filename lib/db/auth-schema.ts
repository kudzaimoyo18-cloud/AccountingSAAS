// package is deprecated and emits a schema that lags the runtime — it omitted
// account.issuer, which made every sign-up fail with a 500).
//
// Names and columns are fixed by the library. After upgrading better-auth or
// adding a plugin, regenerate and run `npm run db:push` rather than editing.
